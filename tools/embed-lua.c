/* Turn Lua source files into C byte arrays. Built with the same compiler as
   lhelper so embedding needs no external Lua interpreter or scripting tools. */

#include <ctype.h>
#include <stdio.h>
#include <string.h>

static const char *module_name(const char *path) {
    const char *name = strrchr(path, '/');
    name = name ? name + 1 : path;
    size_t length = strlen(name);
    if (length <= 4 || strcmp(name + length - 4, ".lua") != 0)
        return NULL;
    for (size_t i = 0; i < length - 4; i++) {
        if (!isalnum((unsigned char)name[i]) && name[i] != '_')
            return NULL;
    }
    return name;
}

int main(int argc, char *argv[]) {
    if (argc < 2) {
        fprintf(stderr, "usage: embed-lua <module.lua>...\n");
        return 1;
    }
    puts("/* Generated by tools/embed-lua.c; do not edit. */");
    for (int i = 1; i < argc; i++) {
        if (!module_name(argv[i])) {
            fprintf(stderr, "embed-lua: invalid module filename: %s\n", argv[i]);
            return 1;
        }
        FILE *file = fopen(argv[i], "rb");
        if (!file) {
            perror(argv[i]);
            return 1;
        }
        printf("static const unsigned char lua_source_%d[] = {\n", i);
        int byte;
        size_t column = 0;
        while ((byte = fgetc(file)) != EOF) {
            printf("0x%02x,", (unsigned int)byte);
            if (++column % 16 == 0) putchar('\n');
        }
        if (ferror(file)) {
            fprintf(stderr, "embed-lua: cannot read %s\n", argv[i]);
            fclose(file);
            return 1;
        }
        fclose(file);
        puts("0x00\n};");
    }
    puts("static const struct embedded_module {\n"
         "    const char *name;\n"
         "    const unsigned char *source;\n"
         "    size_t size;\n"
         "} embedded_modules[] = {");
    for (int i = 1; i < argc; i++) {
        const char *name = module_name(argv[i]);
        printf("    {\"%.*s\", lua_source_%d, sizeof(lua_source_%d) - 1},\n",
               (int)strlen(name) - 4, name, i, i);
    }
    puts("};");
    if (fflush(stdout) == EOF || ferror(stdout)) {
        fprintf(stderr, "embed-lua: cannot write generated header\n");
        return 1;
    }
    return 0;
}
